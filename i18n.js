const LANGS = ['de', 'es', 'en', 'pt'];

let LANG = (() => {
  const url = new URLSearchParams(location.search).get('lang');
  if (LANGS.includes(url)) return url;
  try { const saved = localStorage.getItem('lafita-lang'); if (LANGS.includes(saved)) return saved; } catch (e) {}
  const nav = (navigator.language || 'de').slice(0, 2).toLowerCase();
  return LANGS.includes(nav) ? nav : 'de';
})();

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.de[key] ?? key;
  if (vars && typeof s === 'string') for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

// "Mi, 25.11." / "Wed, 25.11."
function diaCorto(iso) {
  const d = new Date(iso + 'T00:00:00');
  return `${t('days')[d.getDay()]}, ${String(d.getDate()).padStart(2, '0')}.${String(d.getMonth() + 1).padStart(2, '0')}.`;
}

function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.innerHTML = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('.lang-switch button').forEach(b => b.setAttribute('aria-pressed', b.dataset.lang === LANG));
}

function setLang(l) {
  if (!LANGS.includes(l)) return;
  LANG = l;
  try { localStorage.setItem('lafita-lang', l); } catch (e) {}
  applyI18n();
  document.dispatchEvent(new CustomEvent('langchange'));
}

// Selector DE | ES | EN | PT: <div class="lang-switch"></div> en la cabecera
function initLangSwitch() {
  document.querySelectorAll('.lang-switch').forEach(box => {
    box.setAttribute('role', 'group');
    box.setAttribute('aria-label', 'Sprache / Idioma / Language');
    box.innerHTML = LANGS.map(l => `<button type="button" data-lang="${l}">${l.toUpperCase()}</button>`).join('');
    box.addEventListener('click', e => { const b = e.target.closest('button'); if (b) setLang(b.dataset.lang); });
  });
  applyI18n();
}
